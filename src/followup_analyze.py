"""Follow-up analysis (NOT pre-registered; DEVIATIONS.md D5). EXPLORATORY ONLY.

  python src/followup_analyze.py runs/followup_merged.jsonl --out results/followup

instr_tool vs instr in the disclosure environment, all four models. Same estimator as phase2_analyze.py (logistic GEE,
exchangeable within episode, model fixed effects, standardized pp difference, 2,000-resample episode-clustered
bootstrap). No multiplicity correction; no confirmatory claims. Also: per-model rates, strict judge, uptake,
diversion, bypass, false escalations, activity.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import prereg_params as pp  # noqa: E402
from phase2_analyze import bypassed, gee_effect  # noqa: E402
from prereg_data import drafts_df, episodes_df, load_episodes, writes_df  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="+")
    ap.add_argument("--out", default=str(ROOT / "results/followup"))
    ap.add_argument("--n-boot", type=int, default=None)
    a = ap.parse_args()
    P = pp.load()
    an, im = P["prereg"]["analysis"], P["implementation"]
    n_boot, seed = a.n_boot or an["bootstrap_resamples"], im["bootstrap_seed"]
    eps = load_episodes(a.files)
    mock = any(e.get("mock") for e in eps)
    out = Path(a.out)
    if mock and out.resolve().is_relative_to((ROOT / "results").resolve()):
        sys.exit("refusing to write mock results into results/")
    if any(e.get("phase") != "followup" or e.get("judge_pending") for e in eps):
        sys.exit("input must be judged follow-up episodes only")
    out.mkdir(parents=True, exist_ok=True)
    ed, W, D = episodes_df(eps), writes_df(eps), drafts_df(eps)
    W["t"] = (W.arm == "instr_tool").astype(int)

    md = ["# Follow-up readout: instr_tool vs instr (auto-generated by src/followup_analyze.py)\n",
          "**EXPLORATORY. NOT PRE-REGISTERED.** Designed after Phase 2 results were seen (DEVIATIONS.md D5). "
          "Disclosure environment only; fresh seeds 3000-3005; 6 episodes per model per arm. Likely underpowered.",
          f"Episodes: {len(ed)} of {len(pp.followup_trials(P, 'NDA'))} expected. Bootstrap resamples: {n_boot}"
          + (" (OVERRIDDEN)" if a.n_boot else "") + ".", "**MOCK DATA.**" if mock else "", ""]
    rows = []
    for judge, col in [("domain (primary)", "leak"), ("strict", "leak_strict")]:
        r = gee_effect(W.copy(), "t", col, ["arm", "model"], n_boot, seed)
        rows.append(dict(judge=judge, comparison="instr_tool vs instr", **r))
    eff = pd.DataFrame(rows)
    eff.to_csv(out / "EXPLORATORY_followup_effect.csv", index=False)
    cols = [c for c in ["judge", "comparison", "n_writes", "n_episodes", "plr_treat_pct", "plr_ref_pct", "effect_pp",
                        "ci_lo", "ci_hi", "p_two_sided", "boot_failures", "note"] if c in eff]
    md += ["## Effect (pooled, model fixed effects)\n", eff[cols].to_markdown(index=False, floatfmt=".4g"), ""]

    pm = (W.groupby(["model", "arm"]).agg(writes=("leak", "size"), leaks=("leak", "sum"),
                                          episodes=("key", "nunique")).reset_index())
    pm["plr_pct"] = (100 * pm.leaks / pm.writes).round(2)
    pm.to_csv(out / "EXPLORATORY_followup_per_model.csv", index=False)
    md += ["## Per model (descriptive)\n", pm.to_markdown(index=False, floatfmt=".4g"), ""]

    e = ed[ed.arm == "instr_tool"]
    w = W[W.arm == "instr_tool"]
    attempted = int(w.leak.sum() + D.leak.sum())
    thr = an["bypass_similarity"]
    nb = sum(bypassed(r, w[(w.key == r["key"]) & (w.step > r["step"])], thr) for _, r in D.iterrows())
    costs = pd.DataFrame([dict(
        arm=arm, episodes=int((ed.arm == arm).sum()),
        activity_writes_per_episode=round(ed[ed.arm == arm].n_writes.mean(), 3),
        uptake=round((e.n_escalations > 0).mean(), 4) if arm == "instr_tool" else np.nan,
        escalations=len(D) if arm == "instr_tool" else np.nan,
        false_escalation_rate=round(1 - D.leak.mean(), 4) if arm == "instr_tool" and len(D) else np.nan,
        diversion_rate=round(D.leak.sum() / attempted, 4) if arm == "instr_tool" and attempted else np.nan,
        bypass_rate=round(nb / len(D), 4) if arm == "instr_tool" and len(D) else np.nan,
        judge_parse_failures=int(ed[ed.arm == arm].judge_parse_fail.sum()),
        malformed_tool_args=int(ed[ed.arm == arm].n_bad_tool_args.sum())) for arm in ("instr", "instr_tool")])
    costs.to_csv(out / "EXPLORATORY_followup_costs.csv", index=False)
    md += ["## Costs, uptake, diversion\n", costs.to_markdown(index=False, floatfmt=".4g"), ""]
    (out / "readout.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
